# ===========================================================================
#  ThunderBackup 配置模板  thunderbackup.config.ps1
# ---------------------------------------------------------------------------
#  这个文件本身就是一个 PowerShell 脚本，它唯一的任务就是填充 $TBConfig 这个哈希表。
#  不认识键会原样报告出来（运行时打印 "unknown config keys"），拼错的键会被忽略——
#  所以每次改完配置，请跑一次 doctor，第 [13] 节会把"实际读到的值"打回给你看。
#
#  编码：本文件必须是 UTF-8 带 BOM。Windows PowerShell 5.1 对无 BOM 的 .ps1 按 ANSI
#  解码，中文路径会变成乱码——而乱码正好落在用来排除目录的字符串上，保护会看起来生效、
#  实际什么都没拦（本项目真的踩过这个坑）。
#
#  只有 StoreRoot 是必填。其他都有默认值，改错的后果写在每条的「填错会怎样」里。
# ===========================================================================

$TBConfig = @{}

# ---------------------------------------------------------------------------
# 1. 备份库位置（唯一必填）
# ---------------------------------------------------------------------------

# 作用：内容寻址备份库的根目录。所有 blob、索引、日志、观察状态都在这里面。
# 默认值：无（空 = 所有命令直接拒绝运行）。
# 填错会怎样：
#   - 填成迅雷目录或任何被监视目录的子目录 ⇒ 启动即拒绝（TEST-TBSM-PLACEMENT），
#     因为工具会开始备份自己的备份；这不是警告，是不运行。
#   - 填成网络路径或会被休眠的移动盘 ⇒ 每轮扫描都可能卡在 IO 上，用 PerFileDeadlineMs 兜住。
#   - 填在 C 盘而下载在 D 盘 ⇒ 复制要跨卷，原子发布退化成"复制+删除"，断电可留半个 blob
#     （不会污染已发布的库，但那一版会丢）。同卷最省。
# 空间：去重后大约等于你库里"不重复的字节数"。留出 15% 余量，满了会以 BUDGET ABORT 报出来。
$TBConfig['StoreRoot'] = 'E:\ThunderBackup'

# ---------------------------------------------------------------------------
# 2. 监视哪些目录
# ---------------------------------------------------------------------------

# 作用：额外要监视的目录，永远与"从迅雷配置里发现的目录"取并集。
# 默认值：@() 空数组。
# 填错会怎样：多填一个目录只会多花时间扫描；漏填不会漏备份（并集逻辑），除非你改用 manual。
$TBConfig['WatchDirs'] = @()

# 作用：目录集合的取法。
#   auto+extra = 迅雷配置发现的全部候选 ∪ WatchDirs（默认，推荐）
#   manual     = 只用 WatchDirs，完全不做发现
# 默认值：'auto+extra'
# 填错会怎样：这是本工具最容易"静默零备份"的地方。迅雷的下载路径分散在最多 9 个配置键里
#   （TaskDefaultSettings.DefaultPath/InitPath、PathAndCategory.LastUsedPath/historyDownloadPaths、
#   ThunderPanPlugin.defaultDownloadPath/VODCachePath、PrivateSpaceDefaultPath.*、pan-plugin 的
#   default-save-folder 与 recent-folder），只解析出一个键时 doctor 会明确警告。
#   选 manual 又填了一个不存在或空的目录 ⇒ 监视一个空目录，备份 0 个文件，全程无错误。
#   所以：填完先跑 status，它有一条专门的告警"看到 N 个文件、库里 0 个"。
$TBConfig['WatchDirsMode'] = 'auto+extra'

# 作用：永远不碰的目录（前缀匹配，不区分大小写）。迅雷云盘缓存 VODCachePath 会被自动加进来。
# 默认值：@()
# 填错会怎样：填了正在下载的真实目录 ⇒ 那些文件永远不会被备份，而且不会报错。
#   注意备份范围本身就硬排除整个迅雷安装目录（含 Profiles\*.dat*，里面有明文第三方
#   cookie 和明文密码），这条排除写在代码里，配置关掉不了，也不需要关掉。
$TBConfig['SkipDirs'] = @()

# ---------------------------------------------------------------------------
# 3. 完成判据（这个工具最难的部分，改之前先读 README 的 L-01 到 L-04）
# ---------------------------------------------------------------------------

# 作用：额外的"进行中"后缀，与 HKCR 实测确认过的后缀合并（迅雷实测 .xltd / .td）。
# 默认值：@()
# 填错会怎样：把你自己真实文件用的后缀填进来（例如 '.tmp'），那些文件会变成永久 SKIP 候选。
#   工具的规则是：后缀只是"临时名"的证据之一，必须再被 .cfg 边车、hole>0 或持有者之一佐证，
#   否则不认。所以这里加后缀通常没有用，只在迅雷换版本改了命名时才需要。
$TBConfig['TempSuffixesExtra'] = @()

# 作用：静止窗口。最后写入时间早于这个值的文件判 WAIT（暂缓），不允许放行。
# 默认值：20000（毫秒 = 20 秒）
# 填错会怎样：调小 ⇒ 更容易把"写到一半"当成稳定；调大 ⇒ 每个文件至少要等这么久才可能备份。
#   无论怎么调，静止窗口**永远不能证明完成**，它只能推迟判断。这是设计约束，不是参数问题。
$TBConfig['SettleWindowMs'] = 20000

# 作用：迅雷的 .cfg 边车文件被视为"崩溃遗留"而不是"任务未完成"的年龄阈值（分钟）。
#   只有当边车和它的主文件都超过这个年龄、且没有别的活动证据时，才允许忽略边车。
# 默认值：60
# 填错会怎样：调小 ⇒ 一个存在了几十分钟的遗留边车不再挡住备份（可能备份残件）；
#   调大 ⇒ 一个被杀掉的下载任务会把那个文件压成永久 WAIT。
$TBConfig['SidecarTTLMin'] = 60

# 作用：没有完成凭据的文件怎么处理。
#   backup = 照样备份，但标记 BACKUP_UNVERIFIED，在 status 里可见、需要人看（默认）
#   skip   = 不备份（库里不留半截内容，但可恢复的文件数变少）
# 默认值：'backup'
# 填错会怎样：填别的值直接拒绝启动。选 skip 时，本包在没有接入迅雷声明的情况下（README L-04）
#   几乎不会备份任何东西——请保持 'backup'，除非你明确知道自己在削减覆盖面。
$TBConfig['UnverifiedPolicy'] = 'backup'

# ---------------------------------------------------------------------------
# 4. 运行节奏
# ---------------------------------------------------------------------------

# 作用：watch 模式两轮之间的间隔（秒）。
# 默认值：20
# 填错会怎样：低于 5 是浪费 CPU——每一轮都要完整重扫目录树（这是正确性的底座，
#   事件通知不可靠，会丢，所以不靠它）。设 0 或负数会退回默认值。
$TBConfig['IntervalSec'] = 20

# 作用：watch 跑 N 轮后退出。0 = 一直跑，Ctrl+C 停。
# 默认值：0
# 填错会怎样：设成 1 的话改名见证永远拿不到（见证需要"上一轮见过临时名、这一轮消失"），
#   于是所有文件都是 BACKUP_UNVERIFIED。smoke_test 用 2 轮专门验证这一点。
$TBConfig['MaxRounds'] = 0

# 作用：首轮演练。true = 只读诊断照常跑，但一律只报告"本来会做什么"，不写任何东西。
# 默认值：$false
# 填错会怎样：留着 true 就以为在备份，其实什么都没存。跑通之后一定记得改回 $false。
$TBConfig['DryRun'] = $false

# ---------------------------------------------------------------------------
# 5. 每轮预算（防止一轮吃掉整个磁盘和整个 CPU 时间）
# ---------------------------------------------------------------------------
# ★★★ 所有这些"字节"预算都必须按文件长度（EndOfFile）来估算，绝对不能按已分配大小
#     （AllocationSize）估算。实测：一个 eof=512MB、alloc=40MB 的稀疏文件，哈希吞吐
#     135.7 MB/s，和稠密文件的 136.3 MB/s 几乎一样——空洞不免费。
#     AllocationSize 只是"写完没写完"的符号信号（hole=Eof-Alloc，hole>0 一定未完成），
#     把它当成本信号用，一个未完成 50GB 任务的校验成本会被低估 25 倍。★★★

# 作用：单轮最多运行秒数，超了就带着剩余队列退出，并在输出里打 BUDGET ABORT。
# 默认值：120
# 填错会怎样：填 0 或负数 = 一轮跑到天荒地老；被计划任务 5 分钟一启的话会互相叠加。
#   截断永远不会被报成成功，剩余数量会进 skipped.log。
$TBConfig['MaxSecondsPerPass'] = 120

# 作用：单轮最多复制多少字节。0 = 不限。
# 默认值：0
# 填错会怎样：太小 ⇒ 大文件永远排在队首、每轮都在预算边缘（配合 BUDGET ABORT 观察即可）；
#   这条主要是给你控制磁盘占用峰值用的。
$TBConfig['MaxBytesPerPass'] = 0

# 作用：单轮最多提交多少个文件。0 = 不限。
# 默认值：0
# 填错会怎样：同上，纯粹是节奏阀门。
$TBConfig['MaxFilesPerPass'] = 0

# 作用：单个文件超过这个字节数就拒绝提交（进 skipped.log，不静默）。0 = 不设上限。
# 默认值：0
# 填错会怎样：按长度判，不是按占盘判（见上面那条 ★★★）。填成 2GB 而库里有 4K 蓝光原盘
#   ⇒ 那些文件永远不会被备份，只在 skipped.log 里能看到。
$TBConfig['MaxFileBytes'] = 0

# 作用：复制缓冲大小（字节）。
# 默认值：1048576（1 MB）
# 填错会怎样：实测 1/4/16 MB 差异在 3% 以内，所以这不是性能旋钮；调太小只是多几次系统调用。
$TBConfig['BufferSize'] = 1048576

# 作用：单个文件的复制超时（毫秒）。0 = 不设单文件超时。
# 默认值：0
# 填错会怎样：填一个比最大文件实际耗用小很多的值 ⇒ 大文件永远备份不成，每轮都超时。
#   它的用途是防"磁盘在坏道上卡死"，不是限速。参考：SHA-256 约 136 MB/s，1 MB 读+哈希约 8.5 ms。
$TBConfig['PerFileDeadlineMs'] = 0

# ---------------------------------------------------------------------------
# 6. 内容轴（"我写进去的字节和刚才那一版是否一致"）——与完成轴（completionClaimed）正交
# ---------------------------------------------------------------------------

# 作用：提交之后立刻重读 blob 再哈希一次，通过才在该版本上落 contentVerified=true（内容轴）。
# 默认值：$true
# 填错会怎样：设 $false ⇒ 库里所有版本 contentVerified=false，restore 会拒绝恢复它们（除非你加
#   -AllowUnverified）。注意这是**内容轴**（字节没写坏），和"下载完成了吗"是两条正交的轴：
#   完成状态另有 completionClaimed，本开关一个字节都不动它。
#   披露：-AllowUnverified 允许的是【内容轴】未经证明——它只放行"没重哈希过"的字节，
#   不构成任何完成声明；一个用 -AllowUnverified 恢复出来的文件仍然可能是下载中断的半成品。
#   （判据层已把徽章从 Verified 改名为 CompletionClaimed，正是为了这两个词不再互相顶替。）
#   成本参考：256MB 文件约 2 秒。
$TBConfig['VerifyAfterCommit'] = $true

# 作用：增量快速路径。大小+修改时间+创建时间+已分配大小都命中一个"内容已重哈希过"
#   （该版本 contentVerified=true）的版本 ⇒ 跳过重读。命中的是内容轴，与完成轴无关。
# 默认值：$true
# 填错会怎样：关掉 ⇒ 每轮全量重扫重哈希，10 万文件/200GB 约 26 分钟（字节项 200GB÷139MB/s
#   = 24.5 分，文件项 100k×1.1ms = 1.9 分，串行，不含复制）。开着 ⇒ 必须靠 RehashEveryRuns
#   兜住"内容被同长度改写"的情况；把它设 0 又开着 SkipUnchanged，就再也不会重新校验。
$TBConfig['SkipUnchanged'] = $true

# 作用：每 N 轮强制忽略快速路径、完整重读一遍。
# 默认值：30
# 填错会怎样：设 0 = 关掉这个逃生阀（配合上面的 true 就是永久相信旧快照）；设 1 = 每轮全量，
#   等于关掉快速路径。
$TBConfig['RehashEveryRuns'] = 30

# ---------------------------------------------------------------------------
# 7. 观察状态与日志
# ---------------------------------------------------------------------------

# 作用：跨轮观察状态（谁见过哪个临时名、大小怎么变的）最多记多少个文件。
# 默认值：20000
# 填错会怎样：超出会裁剪，被裁掉的条目**丢掉它的改名见证**，于是原本带着完成声明
#   （completionClaimed=true，完成轴）的文件会退回 BACKUP_UNVERIFIED。这不是内容轴的变化：
#   已经落库的字节仍然 contentVerified=true，只是"下载完成了"这句话不再敢讲。
#   status/once 会把裁掉了多少条大声打出来。库比这个大就把它调大。
$TBConfig['StateMaxEntries'] = 20000

# 作用：watch 时逐文件打印判定过程。
# 默认值：$false
# 填错会怎样：开着跑 10 万文件会刷屏并且明显拖慢；只用于排障。
$TBConfig['LogVerbose'] = $false

